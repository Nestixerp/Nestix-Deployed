def default_clauses_for(standard_name: str, version: str):
    """Return the clause skeleton for a standard (short summaries only)."""
    applicable = {"ISO 9001": "Quality", "ISO 14001": "Environmental", "ISO 45001": "OHS", "ISO 19011": "IMS"}.get(standard_name, "IMS")
    out = []
    for num, title, summary in _MSS_CLAUSES:
        if standard_name == "ISO 9001" and num in ("5.4",):
            continue
        if standard_name in ("ISO 14001", "ISO 45001") and num in ("6.3", "8.4", "8.5", "8.6", "8.7"):
            continue
        if standard_name == "ISO 14001" and num == "5.4":
            continue
        out.append({
            "clause_number": num, "clause_title": title, "clause_summary": summary,
            "parent_clause": num.split(".")[0], "audit_prompt": "", "evidence_guidance": "",
            "typical_records": "", "applicable_to": applicable, "active": True,
        })
    return out


